const canvasReady = require('./navigation.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const state = page => page.evaluate(async () => {
  const app = await (await import('/personal/client/main.js')).ready;
  return { page: app.page, camera: app.camera.value };
});
const values = async page => (await state(page)).page.elements;
const value = async (page, id) => (await values(page)).find(e => e.id === id);
const object = (page, id) => page.locator(`[data-id="${id}"]`);
const selection = page => page.locator('.object.selected').evaluateAll(nodes => nodes.map(n => n.dataset.id));
const point = async (page, x, y) => {
  const c = (await state(page)).camera, s = await page.locator('#viewport').boundingBox();
  return { x: s.x + s.width / 2 + (x - c.x) * 24 * c.zoom, y: s.y + s.height / 2 + (y - c.y) * 24 * c.zoom };
};
const click = async (page, x, y) => { const p = await point(page, x, y); await page.mouse.click(p.x, p.y); };
const move = async (page, x, y) => { const p = await point(page, x, y); await page.mouse.move(p.x, p.y); };
const drag = async (page, x, y, dx, dy) => { await move(page, x, y); await page.mouse.down(); const p = await point(page, x + dx, y + dy); await page.mouse.move(p.x, p.y, { steps: 12 }); await page.mouse.up(); };
const undo = page => page.keyboard.press('Control+z');
const redo = page => page.keyboard.press('Control+Shift+z');
const field = async (page, name, value) => { const input = page.locator('#prop-' + name); await input.fill(String(value)); await input.press('Tab'); };
const save = async page => { await page.locator('#save-page').click(); await page.waitForFunction(() => document.querySelector('#save-status').textContent === 'Saved'); };

module.exports = async ({ page, origin, root }) => {
  const fixture = { slug: 'authoring', camera: { x: 0, y: 0, zoom: 1 }, elements: [
    { id: 'a', type: 'text', x: -12, y: -4, width: 4, height: 2, text: 'Alpha', font: 'mono', fontSize: 16 },
    { id: 'b', type: 'text', x: -5, y: -4, width: 4, height: 2, text: 'Beta', font: 'baskerville', fontSize: 20, href: '/personal/#/field-notes', zIndex: 2 },
    { id: 'photo', type: 'image', x: 4, y: -4, width: 4, height: 3, src: '/personal/assets/zion.png', alt: 'photo' },
  ] };
  await fs.writeFile(path.join(root, 'pages/authoring.json'), JSON.stringify(fixture));
  const open = async () => { await page.goto(origin + '/personal/?edit5500#/authoring'); await canvasReady(page); await page.waitForSelector('#editor-tools'); };
  await open();
  await click(page, -11, -3); assert.deepEqual(await selection(page), ['a']);
  await page.keyboard.down('Shift'); await click(page, -4, -3); await page.keyboard.up('Shift');
  assert.deepEqual(await selection(page), ['a', 'b']);
  await page.keyboard.down('Shift'); await click(page, -4, -3); await page.keyboard.up('Shift');
  assert.deepEqual(await selection(page), ['a']);
  await page.keyboard.down('Shift'); await click(page, -4, -3); await page.keyboard.up('Shift');
  await page.evaluate(async () => (await (await import('/personal/client/main.js')).ready).camera.set({ x: -1, y: 0, zoom: 1.5 }));
  await drag(page, -11, -3, 2.2, 1.1);
  for (const id of ['a', 'b']) { const e = await value(page, id), start = fixture.elements.find(e => e.id === id); assert.equal(e.x, start.x + 2); assert.equal(e.y, start.y + 1); }
  const groupMoved = await values(page);
  assert.equal(new URL(page.url()).hash, '#/authoring');
  await undo(page); assert.deepEqual(await values(page), fixture.elements, 'one undo restores the entire group gesture');
  await page.waitForFunction(() => document.querySelector('#save-status').textContent === 'Saved');
  await redo(page); assert.deepEqual(await values(page), groupMoved);
  await page.keyboard.press('Delete'); assert.deepEqual((await values(page)).map(e => e.id), ['photo']);
  await undo(page); assert.deepEqual(await values(page), groupMoved);
  await undo(page); assert.deepEqual(await values(page), fixture.elements);
  // Marquee selects intersecting objects without moving the camera.
  await page.keyboard.press('Escape');
  const camera = (await state(page)).camera;
  await drag(page, -13, -5, 13, 4);
  assert.deepEqual(await selection(page), ['a', 'b']); assert.deepEqual((await state(page)).camera, camera);
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('Shift+ArrowDown');
  assert.equal((await value(page, 'a')).x, -11); assert.equal((await value(page, 'b')).y, 1);
  await undo(page); await undo(page);
  await page.keyboard.press('Control+c');
  await page.keyboard.press('Control+v');
  assert.equal((await values(page)).length, 5);
  const pasted = (await values(page)).slice(3);
  assert.equal(new Set((await values(page)).map(e => e.id)).size, 5);
  for (let i = 0; i < 2; i++) assert.deepEqual({ ...pasted[i], id: fixture.elements[i].id, x: pasted[i].x - 1, y: pasted[i].y - 1 }, fixture.elements[i]);
  await undo(page); assert.deepEqual(await values(page), fixture.elements);
  await drag(page, -13, -5, 13, 4);
  await page.keyboard.press('Control+d'); assert.equal((await values(page)).length, 5);
  await undo(page); assert.deepEqual(await values(page), fixture.elements);
  await drag(page, -13, -5, 13, 4);
  await page.keyboard.press('Control+x'); assert.deepEqual((await values(page)).map(e => e.id), ['photo']);
  await undo(page); assert.deepEqual(await values(page), fixture.elements);
  // Copy survives navigation to a different canvas; test the empty-clipboard fallback.
  await page.goto(origin + '/personal/?edit5500#/field-notes'); await canvasReady(page);
  await page.waitForSelector('#editor-tools');
  const destination = await values(page);
  await page.evaluate(() => document.body.dispatchEvent(new ClipboardEvent('paste', { clipboardData: new DataTransfer(), bubbles: true, cancelable: true })));
  assert.equal((await values(page)).length, destination.length + 2);
  assert.equal((await values(page)).at(-2).text, 'Alpha');
  assert.equal((await values(page)).at(-1).text, 'Beta');
  await undo(page); assert.deepEqual(await values(page), destination);
  await open();

  await click(page, -11, -3); await page.locator('#prop-locked').check();
  assert.equal(await object(page, 'a').locator('.resize-handle').count(), 0);
  assert.equal(await page.locator('#prop-x').isDisabled(), true);
  await drag(page, -11, -3, 1, 1); assert.equal((await value(page, 'a')).x, -12);
  await page.keyboard.press('ArrowRight'); assert.equal((await value(page, 'a')).x, -12);
  await page.locator('#prop-locked').uncheck();
  await page.keyboard.down('Alt'); await drag(page, -11, -3, 0.4, 0.3); await page.keyboard.up('Alt');
  assert.ok(Math.abs((await value(page, 'a')).x + 11.6) < 1e-6);
  await undo(page); assert.equal((await value(page, 'a')).x, -12);
  const h = await object(page, 'a').locator('[data-handle=both]').boundingBox();
  await page.keyboard.down('Alt'); await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await page.mouse.down();
  await page.mouse.move(h.x + h.width / 2 + 12, h.y + h.height / 2 + 12, { steps: 5 }); await page.mouse.up(); await page.keyboard.up('Alt');
  assert.equal((await value(page, 'a')).width, 4.5); await undo(page);
  await page.locator('#prop-shadow').check();
  await field(page, 'lineHeight', 2); await field(page, 'letterSpacing', -0.02);
  await page.locator('#prop-font').selectOption('baskerville');
  const typography = await object(page, 'a').evaluate(el => ({ shadow: getComputedStyle(el).boxShadow, lineHeight: getComputedStyle(el).lineHeight, spacing: getComputedStyle(el).letterSpacing, width: el.style.width }));
  assert.equal(typography.lineHeight, '32px'); assert.equal(typography.spacing, '-0.32px'); assert.equal(typography.width, '96px'); assert.match(typography.shadow, /14px/);
  await page.locator('#edit-text').click();
  await page.keyboard.press('Control+a'); await page.keyboard.insertText('A long sentence that wraps across several lines.\nAnother line.');
  const typed = (await value(page, 'a')).text;
  await page.keyboard.press('Control+z'); assert.equal((await value(page, 'a')).text, 'Alpha', 'native undo affects text, not canvas history');
  await page.keyboard.press('Control+Shift+z'); assert.equal((await value(page, 'a')).text, typed);
  await page.keyboard.press('ArrowLeft'); await page.keyboard.press('Shift+ArrowRight'); await page.keyboard.press('Control+c');
  await page.keyboard.press('Control+v'); assert.equal((await values(page)).length, 3, 'native text paste must not paste objects');
  await page.keyboard.press('Escape');
  await undo(page); assert.equal((await value(page, 'a')).text, 'Alpha'); await redo(page);
  await click(page, -11, -3);
  await page.waitForFunction(() => document.querySelector('[data-id=a]').dataset.overflow === 'true');
  const beforeFocus = (await state(page)).camera;
  await page.locator('#focus-selected').click();
  assert.equal(await page.locator('#focus-content > div').evaluate(el => getComputedStyle(el).lineHeight), '32px');
  assert.equal(await page.locator('#focus-content > div').evaluate(el => getComputedStyle(el).letterSpacing), '-0.32px');
  await page.keyboard.press('Escape'); assert.deepEqual((await state(page)).camera, beforeFocus);
  await save(page);
  const saved = (await state(page)).page; await page.reload(); await page.waitForSelector('#editor-tools'); assert.deepEqual((await state(page)).page, saved);
  await click(page, 5, -3); await page.locator('#prop-shadow').check();
  assert.match(await object(page, 'photo').evaluate(el => getComputedStyle(el).boxShadow), /14px/);

  // Orthogonal drawing: preview, flipped elbow, backspace, finish as one edit.
  await page.locator('#add-line').click(); assert.equal(await page.locator('#line-mode').inputValue(), 'orthogonal');
  await click(page, -10, 1); await move(page, -5.2, 3.2);
  assert.equal(await page.locator('.line-draft .line-ink').getAttribute('points'), '0,0 120,0 120,48');
  await click(page, -5.2, 3.2);
  await move(page, 0, 0); await page.keyboard.press('Tab');
  assert.equal(await page.locator('.line-draft .line-ink').getAttribute('points'), '0,24 120,24 120,72 120,0 240,0');
  await click(page, 0, 0); await page.keyboard.press('Backspace');
  await move(page, 1, 0); await page.keyboard.press('Enter');
  const poly = (await values(page)).at(-1);
  assert.deepEqual(poly.points, [[-10, 1], [-5, 1], [-5, 3], [-5, 0], [1, 0]]);
  await undo(page); assert.equal(await object(page, poly.id).count(), 0);
  await redo(page); await click(page, -7, 1);
  assert.equal(await object(page, poly.id).locator('.resize-handle').count(), 5);
  await drag(page, -5, 1, 1.2, -1.1);
  assert.deepEqual((await value(page, poly.id)).points[1], [-4, 0]);
  await undo(page); assert.deepEqual((await value(page, poly.id)).points, poly.points);
  const segment = await point(page, -8, 1); await page.mouse.dblclick(segment.x, segment.y);
  assert.deepEqual((await value(page, poly.id)).points[1], [-8, 1]);
  await page.locator('#prop-strokeStyle').selectOption('dotted'); await field(page, 'strokeWidth', 1.5); await page.locator('#prop-arrowhead').check(); await field(page, 'zIndex', 10);
  const beforeMove = await value(page, poly.id);
  await drag(page, -9, 1, 1, -1);
  assert.deepEqual((await value(page, poly.id)).points, beforeMove.points.map(([x, y]) => [x + 1, y - 1]));
  await undo(page); await field(page, 'zIndex', -3);
  await page.locator('#add-line').click(); await click(page, 1, 2); await move(page, 5, 3); await page.keyboard.press('Escape');
  assert.equal(await page.locator('.line-draft').count(), 0); assert.equal((await values(page)).length, 4);
  await page.locator('#add-line').click(); await page.locator('#line-mode').selectOption('direct');
  await click(page, 2, 1); const end = await point(page, 6, 3); await page.mouse.dblclick(end.x, end.y);
  assert.deepEqual((await values(page)).at(-1).points, [[2, 1], [6, 3]]);
  await page.keyboard.press('Control+c'); await page.keyboard.press('Control+d');
  const clone = (await values(page)).at(-1);
  assert.deepEqual(clone.points, [[3, 2], [7, 4]]);
  await save(page); const final = (await state(page)).page;
  await page.reload(); await page.waitForSelector('#editor-tools'); assert.deepEqual((await state(page)).page, final);
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(root, 'pages/authoring.json'), 'utf8')), final);
  await page.screenshot({ path: '/tmp/space-authoring.png' });
  console.log('Authoring verified: selection/marquee, grouped movement/history, native text undo, clipboard, typography, shadows, locks, Alt snapping, polyline drawing/editing and persistence.');
};
